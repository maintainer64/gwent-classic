export const plural = (n: number, forms: [string, string, string]) =>
  forms[
    n % 10 === 1 && n % 100 !== 11
      ? 0
      : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14)
        ? 1
        : 2
  ]
export const cardsText = (n: number) => `${n} ${plural(n, ['карта', 'карты', 'карт'])}`
export const abilities = (value: string) =>
  value
    .split(' ')
    .filter((x) => ABILITIES[x])
    .map((x) => ABILITIES[x])
    .join(' · ')
